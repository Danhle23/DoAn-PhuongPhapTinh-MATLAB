function res = tichphan_hinhthang(mode, arg1, arg2, arg3, arg4)
% TICHPHAN_HINHTHANG Tinh tich phan xac dinh bang quy tac Hinh thang mo rong
% Ho tro 2 che do:
%   - mode = 'data': tichphan_hinhthang('data', x, y) (ho tro ca moc cach deu & khong deu)
%   - mode = 'func': tichphan_hinhthang('func', f_input, a, b, N)

    if strcmpi(mode, 'data')
        [x, sortIdx] = sort(arg1(:)');
        y = arg2(:)';
        y = y(sortIdx);
        n = numel(x);
        if n ~= numel(y) || n < 2
            error('Du lieu x va y phai co cung do dai va it nhat 2 diem!');
        end

        dx = diff(x);
        sub_areas = 0.5 * dx .* (y(1:end-1) + y(2:end));
        I = sum(sub_areas);

        res = struct( ...
            'method', 'Hinh thang (Du lieu x, y)', ...
            'mode', 'data', ...
            'I', I, ...
            'I_exact', NaN, ...
            'abs_err', NaN, ...
            'N', n - 1, ...
            'h', mean(dx), ...
            'x_nodes', x, ...
            'y_nodes', y, ...
            'weights', [], ...
            'formula', 'I = sum_{i=1}^{N} (x_{i+1} - x_i)/2 * (y_i + y_{i+1})');
    else
        [f, ~] = parse_math_func(arg1);
        a = arg2;
        b = arg3;
        N = round(arg4);
        if N < 1
            error('So khoang chia N phai la so nguyen duong (N >= 1)!');
        end

        h = (b - a) / N;
        x_nodes = linspace(a, b, N + 1);
        y_nodes = f(x_nodes);

        w = 2 * ones(1, N + 1);
        w(1) = 1;
        w(end) = 1;
        I = (h / 2) * sum(w .* y_nodes);

        I_exact = integral(f, a, b, 'RelTol', 1e-12, 'AbsTol', 1e-14);

        res = struct( ...
            'method', 'Hinh thang (Ham so)', ...
            'mode', 'func', ...
            'I', I, ...
            'I_exact', I_exact, ...
            'abs_err', abs(I - I_exact), ...
            'N', N, ...
            'h', h, ...
            'x_nodes', x_nodes, ...
            'y_nodes', y_nodes, ...
            'weights', w * (h / 2), ...
            'formula', 'I = (h/2) * [y_0 + 2*(y_1 + ... + y_{N-1}) + y_N]');
    end
end
